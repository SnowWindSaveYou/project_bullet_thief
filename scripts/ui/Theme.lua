-- ═══════════════════════════════════════════
-- 辅助函数
-- ═══════════════════════════════════════════

--- 返回 nvgRGBAf 参数（展开 table）
function M.c(colorTable)
    return colorTable[1], colorTable[2], colorTable[3], colorTable[4] or 1.0
end

--- 返回带自定义 alpha 的颜色
function M.ca(colorTable, alpha)
    return colorTable[1], colorTable[2], colorTable[3], alpha
end

